"""Label-leakage test: caption <-> ocr_text vocabulary overlap (plan §P0.9,
PRD §6.1.3/§6.1.2). Reuses `content_words()` from `eval/build_eval_set.py` --
the exact same Jaccard-on-content-words primitive already used there to flag
near-duplicate captions, applied here to a different pair of texts.

Why this matters more than a generic QA check: the ground-truth caption was
generated by Gemini looking at the *answer* keyframe (PRD §6.1.2). If Gemini
transcribed on-screen text into that caption, then the `ocr` channel's score
is the system finding text Gemini already copied out of the same frame, not
real cross-modal retrieval -- CLAUDE.md §3's "model sinh nhãn != model bị
đánh giá" invariant would be violated in substance even though BEiT-3/OCR
and Gemini remain formally different models.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from eval.build_eval_set import content_words


@dataclass(frozen=True)
class LeakageRecord:
    """One ground-truth query joined with the OCR text of every keyframe
    that falls inside its `[start_sec, end_sec]` window (there can be more
    than one -- up to 4 keyframes per shot, PRD §F1)."""

    video_id: str
    order_index: int
    caption: str
    ocr_texts: Sequence[str]


@dataclass(frozen=True)
class LeakageReport:
    total: int
    mean_overlap: float
    median_overlap: float
    high_overlap_count: int
    high_overlap_rate: float
    threshold: float


def caption_ocr_jaccard(caption: str, ocr_texts: Sequence[str], stopwords: frozenset[str]) -> float:
    """Max Jaccard overlap (not mean) between the caption's content words and
    any single keyframe's OCR content words -- only one keyframe needs to
    leak for the caption to be compromised. Returns 0.0 (not an error) when
    `ocr_texts` is empty or the caption has no content words at all: missing
    OCR coverage for a shot is expected data while OCR is still partial
    (plan §P0.7 note), not a failure of this function."""
    caption_words = content_words(caption, stopwords)
    if not caption_words:
        return 0.0

    best = 0.0
    for text in ocr_texts:
        ocr_words = content_words(text, stopwords)
        if not ocr_words:
            continue
        union = caption_words | ocr_words
        jaccard = len(caption_words & ocr_words) / len(union) if union else 0.0
        best = max(best, jaccard)
    return best


def compute_leakage_report(
    records: Sequence[LeakageRecord], stopwords: frozenset[str], threshold: float
) -> LeakageReport:
    """Aggregates `caption_ocr_jaccard` over every ground-truth record.
    `threshold` is a reporting cutoff, not a quality gate here -- unlike
    `eval/build_eval_set.py`'s 30% rejection-rate gate, this test is meant to
    be read by a human (CLAUDE.md §4: "hệ thống interactive -- con người
    chốt đáp án cuối"), not to silently refuse to write a report."""
    if not records:
        raise ValueError("compute_leakage_report: records is empty")

    overlaps = [caption_ocr_jaccard(r.caption, r.ocr_texts, stopwords) for r in records]
    overlaps_sorted = sorted(overlaps)
    n = len(overlaps_sorted)
    mid = n // 2
    median = (
        overlaps_sorted[mid]
        if n % 2 == 1
        else (overlaps_sorted[mid - 1] + overlaps_sorted[mid]) / 2.0
    )
    high_overlap_count = sum(1 for overlap in overlaps if overlap >= threshold)

    return LeakageReport(
        total=n,
        mean_overlap=sum(overlaps) / n,
        median_overlap=median,
        high_overlap_count=high_overlap_count,
        high_overlap_rate=high_overlap_count / n,
        threshold=threshold,
    )
